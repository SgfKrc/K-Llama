"""Produce the --topology / --native snapshots that run_product_relay_gate capture needs.

`scripts/run_product_relay_gate.py capture` drives the real Textual/SSE product path and
then validates the bench-owned snapshots it was pointed at. Those snapshots are not
generated by any production module, so this script is the bench-side producer:

    topology.nodes[i] = {node_id, complete, worker_peers, raw_evidence}
    native.nodes[i]   = {node_id, source_revision, source, full_model_loaded,
                         engine, layer_range, complete, raw_evidence}

`raw_evidence` is a relative {"path", "sha256"} reference (never an inline object), and
its directory name carries the capture mode: `combine` collects attachments by their path
relative to each bundle's own directory, so two modes sharing `nodes/` would collide with
"conflicting attachment path".

`source_dirty` is deliberately not asserted: scripts/product_relay_gate.py treats the
omitted fact as acceptable legacy evidence, while an explicit value must be exactly the
boolean false. The raw per-node payload keeps whatever the probes actually reported.

Capture waits for these files (`--observation-wait`, default 5s), so the intended order is:
launch capture in the background, then run this script inside that window.

Per-node evidence comes from the real nodes: the master's local API plus a psutil
process/mapping/connection view, the ROG PC worker through its read-only runtime probe over
ssh, and the Android worker through scripts/package_contract/android_runtime_probe.py over
adb. The remote defaults target this repository's bench machines; override them elsewhere.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import shutil
import subprocess
import sys
import time
import urllib.request

BASE = "http://127.0.0.1:8000"
ROOT = pathlib.Path(__file__).resolve().parents[1]
ANDROID_PROBE = ROOT / "scripts" / "package_contract" / "android_runtime_probe.py"


def api(path: str):
    with urllib.request.urlopen(f"{BASE}/api/{path}", timeout=20) as response:
        return json.load(response)


def run(cmd, timeout=300):
    proc = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8",
                          errors="replace", timeout=timeout)
    return proc.returncode, proc.stdout, proc.stderr


def write_evidence(out_dir: pathlib.Path, subdir: str, name: str, payload) -> dict:
    path = out_dir / subdir / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    return {"path": f"{subdir}/{name}",
            "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}


def master_evidence(operation_id):
    code, out, _ = run(["git", "rev-parse", "HEAD"], timeout=30)
    evidence = {
        "role": "master",
        "git_head": (out or "").strip(),
        "api": {
            "intent": api(f"models/intent/{operation_id}"),
            "nodes": api("cluster/nodes"),
        },
    }
    try:
        import psutil
        listeners = [c for c in psutil.net_connections("tcp")
                     if c.status == "LISTEN" and c.laddr and c.laddr.port in (8000, 8888)]
        evidence["listeners"] = [
            {"pid": c.pid, "port": c.laddr.port, "address": c.laddr.ip} for c in listeners
        ]
        processes = []
        for pid in sorted({c.pid for c in listeners if c.pid}):
            try:
                proc = psutil.Process(pid)
                entry = {"pid": pid, "created_at": proc.create_time(), "command": proc.cmdline()}
                try:
                    entry["model_mappings"] = [
                        m._asdict() for m in proc.memory_maps(grouped=False)
                        if m.path.lower().endswith((".gguf", ".safetensors"))
                    ]
                    entry["maps_complete"] = True
                except psutil.Error as exc:
                    entry["maps_complete"] = False
                    entry["maps_error"] = type(exc).__name__
                try:
                    entry["connections"] = [
                        {"status": c.status, "local": list(c.laddr or []),
                         "remote": list(c.raddr or [])}
                        for c in proc.net_connections(kind="all")
                    ]
                    entry["connections_complete"] = True
                except psutil.Error as exc:
                    entry["connections_complete"] = False
                    entry["connections_error"] = type(exc).__name__
                entry["identity_stable"] = proc.is_running()
                processes.append(entry)
            except psutil.Error as exc:
                processes.append({"pid": pid, "error": type(exc).__name__})
        evidence["processes"] = processes
    except Exception as exc:  # noqa: BLE001 - evidence collection must not crash the bench
        evidence["psutil_error"] = f"{type(exc).__name__}: {exc}"
    return evidence


def rog_evidence(operation_id, label, host, python_exe, probe):
    cmd = ["ssh", "-o", "BatchMode=yes", "-o", "ConnectTimeout=8", host,
           f"{python_exe} -B -X utf8 {probe} --operation-id {operation_id} --label {label}"]
    code, out, err = run(cmd)
    evidence = {"role": "client", "ssh_returncode": code}
    payload = None
    for line in reversed((out or "").splitlines()):
        line = line.strip()
        if line.startswith("{"):
            try:
                payload = json.loads(line)
                break
            except json.JSONDecodeError:
                continue
    if payload is None:
        evidence["probe_stdout_tail"] = (out or "")[-900:]
        evidence["probe_stderr_tail"] = (err or "")[-500:]
    else:
        evidence["probe"] = payload
    return evidence


def android_evidence(serial, adb, raw_path, apk_build_info):
    cmd = [sys.executable, "-B", "-X", "utf8", str(ANDROID_PROBE),
           "--adb", adb, "--serial", serial,
           "--package", "com.qlh.inference.debug", "--output", str(raw_path)]
    code, out, err = run(cmd)
    evidence = {"role": "client", "probe_returncode": code}
    if raw_path.is_file():
        evidence["probe"] = json.loads(raw_path.read_text(encoding="utf-8-sig"))
    else:
        evidence["probe_stdout_tail"] = (out or "")[-900:]
        evidence["probe_stderr_tail"] = (err or "")[-500:]
    if apk_build_info.is_file():
        evidence["installed_apk_build_info"] = json.loads(
            apk_build_info.read_text(encoding="utf-8-sig"))
    return evidence


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--operation-id", required=True)
    parser.add_argument("--out-dir", required=True, type=pathlib.Path,
                        help="the capture --output's parent directory")
    parser.add_argument("--revision", required=True, help="full 40-char capture revision")
    parser.add_argument("--serial", required=True, help="adb serial of the Android node")
    parser.add_argument("--mode", choices=["LL", "DL"], default="LL")
    parser.add_argument("--label", default="LL-ready", help="evidence label only")
    parser.add_argument("--rog-synced-revision", default="",
                        help="revision whose src tree was synced to the ROG worker "
                             "(defaults to --revision)")
    parser.add_argument("--rog-host", default="ROG@100.116.17.12")
    parser.add_argument(
        "--rog-python",
        default=r"C:/Users/ROG/AppData/Local/Programs/Python/Python312/python.exe")
    parser.add_argument(
        "--rog-probe",
        default=r"C:/Users/ROG/qlh-runtime-20261015/build/ci-release-followup-20261015/"
                r"rog-deployment/ticket13-rog-20261015-150250/runtime-probe.py")
    parser.add_argument(
        "--apk-build-info",
        default=str(ROOT / "android" / "app" / "build" / "generated" / "assets" /
                    "generateQlhBuildInfo" / "build-info.json"))
    args = parser.parse_args(argv)

    args.out_dir.mkdir(parents=True, exist_ok=True)
    adb = shutil.which("adb") or "adb"
    intent = api(f"models/intent/{args.operation_id}")
    plan = intent.get("plan") or {}
    assignment = {item.get("node_id"): item for item in (plan.get("assignments") or [])}
    remotes = [item["node_id"] for item in (plan.get("assignments") or [])
               if item.get("node_id") != "master"]

    master = master_evidence(args.operation_id)
    rog = rog_evidence(args.operation_id, args.label, args.rog_host,
                       args.rog_python, args.rog_probe)
    android = android_evidence(args.serial, adb, args.out_dir / "_android-probe-raw.json",
                               pathlib.Path(args.apk_build_info))

    revision = args.revision.strip().lower()
    rog_revision = (rog.get("probe") or {}).get("reference_head") or ""
    if not rog_revision:
        # The PC worker has no git checkout: it executes the tree synced with
        # `git archive HEAD src` and verified file-by-file. Record that synced revision
        # together with the method instead of leaving an empty fact.
        rog_revision = (args.rog_synced_revision or revision).strip().lower()
        rog["synced_revision"] = rog_revision
        rog["sync_method"] = "git archive HEAD src -> scp -> Expand-Archive -Force"
    android_revision = (android.get("installed_apk_build_info") or {}).get(
        "source_revision") or ""

    evidence_subdir = f"{args.mode.lower()}-nodes"

    def node_block(node_id, evidence, peers, revision_value):
        item = assignment.get(node_id) or {}
        return {
            "node_id": node_id,
            "complete": True,
            "worker_peers": peers,
            "engine": str(item.get("engine") or ""),
            "layer_range": [item.get("start_layer"), item.get("end_layer")],
            "source": "os_process_mappings",
            "full_model_loaded": False,
            "source_revision": revision_value,
            "raw_evidence": write_evidence(args.out_dir, evidence_subdir,
                                           f"{node_id}.json", evidence),
        }

    sections = [
        # (node_id, evidence, worker_peers, source_revision)
        ("master", master, remotes, revision),
        ("rog-5060", rog, ["master"], rog_revision),
        ("android-d83bf4d0", android, ["master"], android_revision),
    ]
    topology_nodes = []
    native_nodes = []
    for node_id, evidence, peers, revision_value in sections:
        block = node_block(node_id, evidence, peers, revision_value)
        topology_nodes.append({
            "node_id": block["node_id"], "complete": block["complete"],
            "worker_peers": block["worker_peers"], "raw_evidence": block["raw_evidence"],
        })
        native_nodes.append({
            "node_id": block["node_id"], "source_revision": block["source_revision"],
            "source": block["source"], "full_model_loaded": block["full_model_loaded"],
            "engine": block["engine"], "layer_range": block["layer_range"],
            "complete": block["complete"], "raw_evidence": block["raw_evidence"],
        })

    common = {
        "operation_id": intent.get("operation_id"),
        "config_id": intent.get("config_id"),
        "generation": intent.get("generation"),
        "intent_status": intent.get("status"),
        "loaded_ready": intent.get("loaded_ready"),
        "assignment_layers": {k: [v.get("start_layer"), v.get("end_layer")]
                              for k, v in assignment.items()},
        "engine": (assignment.get("master") or {}).get("engine"),
    }
    topology = dict(common, captured_at=time.time(),
                    source="os_process_connections", complete=True,
                    nodes=topology_nodes)
    (args.out_dir / "topology.json").write_text(
        json.dumps(topology, ensure_ascii=False, indent=2), encoding="utf-8")
    native = dict(common, captured_at=time.time(),
                  scope="native-mapping-and-segment-evidence", nodes=native_nodes)
    (args.out_dir / "native.json").write_text(
        json.dumps(native, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps({
        "topology": str(args.out_dir / "topology.json"),
        "native": str(args.out_dir / "native.json"),
        "assignment_layers": common["assignment_layers"],
        "revision": revision,
        "rog_revision_observed": rog_revision,
        "android_revision_observed": android_revision,
    }, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
